#!/usr/bin/env python3
"""Merge registry/features.d/*.json into registry/features.json and docs/FEATURE_MATRIX.md.

Each entry needs: id, owner_domain, title, state, source_files, tests, remaining_risks, last_verified.
Optional: dependencies, visual_evidence, API_contract, migration, target_ids (ids in legacy_target_registry.json).
"""
from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATES = ["production_verified", "staging_verified", "developed_unverified", "legacy_implemented", "legacy_broken",
          "planned", "blocked"]
REQUIRED = ["id", "owner_domain", "title", "state", "source_files", "tests", "remaining_risks", "last_verified"]


def main() -> int:
    feats, problems = [], []
    for f in sorted((ROOT / "registry" / "features.d").glob("*.json")):
        try:
            data = json.loads(f.read_text())
        except json.JSONDecodeError as exc:
            problems.append(f"{f.name}: invalid JSON ({exc})")
            continue
        items = data.get("features", data) if isinstance(data, dict) else data
        for it in items:
            missing = [k for k in REQUIRED if k not in it]
            if missing:
                problems.append(f"{f.name}:{it.get('id')}: missing {missing}")
            if it.get("state") not in STATES:
                problems.append(f"{f.name}:{it.get('id')}: unknown state {it.get('state')}")
            it["_file"] = f.name
            feats.append(it)
    ids = Counter(x.get("id") for x in feats)
    problems += [f"duplicate id {k}" for k, n in ids.items() if n > 1]

    target = json.loads((ROOT / "registry" / "legacy_target_registry.json").read_text())["features"]
    target_ids = {t["id"] for t in target}
    linked = defaultdict(list)
    for x in feats:
        for t in x.get("target_ids", []) or []:
            if t in target_ids:
                linked[t].append(x["id"])

    out = {"generated_from": "registry/features.d", "states": STATES, "count": len(feats),
           "by_state": Counter(x.get("state") for x in feats), "features": [{k: v for k, v in x.items() if k != "_file"}
                                                                             for x in feats],
           "target_coverage": {"targets": len(target_ids), "linked": len(linked),
                               "unlinked_priority_P0": sorted(t["id"] for t in target
                                                              if t["priority"] == "P0" and t["id"] not in linked)}}
    (ROOT / "registry" / "features.json").write_text(json.dumps(out, indent=2, default=dict) + "\n")

    lines = ["# VOLTORA feature matrix", "",
             "Generated by `python3 registry/build.py` from `registry/features.d/*.json`. States: "
             "`staging_verified` = automated tests (and a real browser check for UI) passed in the development "
             "environment; `developed_unverified` = code exists but acceptance evidence is incomplete; nothing here is "
             "`production_verified`.", "",
             "## Summary", "", "| State | Count |", "|---|---|"]
    for s in STATES:
        lines.append(f"| {s} | {out['by_state'].get(s, 0)} |")
    lines += ["", f"Target registry coverage: {len(linked)} of {len(target_ids)} scoped requirements in "
                  "`legacy_target_registry.json` are linked to at least one delivered feature. "
                  f"Unlinked P0 targets: {len(out['target_coverage']['unlinked_priority_P0'])}.", ""]
    by_domain = defaultdict(list)
    for x in feats:
        by_domain[x["owner_domain"]].append(x)
    for d in sorted(by_domain):
        lines += [f"## {d}", "", "| ID | Feature | State | Tests | Remaining risks |", "|---|---|---|---|---|"]
        for x in sorted(by_domain[d], key=lambda y: y["id"]):
            tests = x.get("tests") or []
            tests_s = ", ".join(tests[:3]) + (" …" if len(tests) > 3 else "") if isinstance(tests, list) else str(tests)
            risks = x.get("remaining_risks") or []
            risks_s = "; ".join(risks[:2]) if isinstance(risks, list) else str(risks)
            lines.append(f"| `{x['id']}` | {x['title']} | {x['state']} | {tests_s} | {risks_s} |")
        lines.append("")
    if problems:
        lines += ["## Ledger problems", ""] + [f"- {p}" for p in problems]
    (ROOT / "docs" / "FEATURE_MATRIX.md").write_text("\n".join(lines) + "\n")
    print(f"{len(feats)} features, {len(problems)} problems")
    for p in problems:
        print("  -", p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
